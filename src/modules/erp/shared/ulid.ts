// ERP shared kernel — public identifier generation.
//
// Per the system-design blueprint ("Data layer on TiDB", rule 6): internal
// primary keys are opaque; clients only ever see a ULID public_id. TiDB uses
// BIGINT AUTO_RANDOM internally; this stack uses cuid/uuid PKs (Prisma) and
// exposes the same ULID public_id contract, so the API surface is identical
// to the blueprint and extraction-friendly.

import { randomBytes } from "node:crypto";

// Crockford base32 (no I, L, O, U) — the ULID alphabet.
const ENCODING = "0123456789ABCDEFGHJKMNPQRSTVWXYZ";
const TIME_LEN = 10; // 48-bit timestamp -> 10 chars
const RANDOM_LEN = 16; // 80-bit randomness -> 16 chars

/** Generate a 26-char ULID: 10-char millisecond timestamp + 16-char random.
 *  Monotonic within a process via a small random increment on same-ms calls
 *  (sort-safe for events created in the same millisecond). */
let lastTime = 0;
let lastRandom = 0n;

export function ulid(now: number = Date.now()): string {
  let time = now;
  let rand: bigint;
  if (time === lastTime) {
    // Same millisecond: increment the previous random value (monotonic ULID).
    rand = (lastRandom + 1n) & ((1n << 80n) - 1n);
  } else {
    lastTime = time;
    rand = BigInt("0x" + randomBytes(10).toString("hex"));
  }
  lastRandom = rand;

  let out = "";
  for (let i = TIME_LEN - 1; i >= 0; i--) {
    out = ENCODING[Number(time % 32)] + out;
    time = Math.floor(time / 32);
  }
  let r = rand;
  let randPart = "";
  for (let i = 0; i < RANDOM_LEN; i++) {
    randPart = ENCODING[Number(r % 32n)] + randPart;
    r >>= 5n;
  }
  return out + randPart;
}

/** True when `s` looks like a ULID generated by this module. */
export function isUlid(s: string): boolean {
  return /^[0-9ABCDEFGHJKMNPQRSTVWXYZ]{26}$/.test(s);
}
