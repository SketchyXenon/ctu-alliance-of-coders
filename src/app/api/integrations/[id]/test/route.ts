import { NextResponse } from "next/server";
import { db } from "@/lib/db";
import { requireAdmin } from "@/lib/auth";
import { rateLimit } from "@/lib/security";
import { logActivity } from "@/lib/activity";
import { withPrismaError } from "@/lib/route-helpers";
import { CACHE_NO_STORE, withCache } from "@/lib/cache";
import { logger } from "@/lib/logger";
import {
  getIntegrationDef,
  validateConfig,
  serializeConfig,
  generateWebhookSecret,
  maskSecret,
  parseConfig,
  type IntegrationDef,
} from "@/lib/integrations";

/**
 * POST /api/integrations/[id]/test - admin only.
 * Verifies an integration is correctly configured. Behavior depends on kind:
 *
 *  - webhook: enables the integration (generating a key if none exists) and
 *    returns the signing key + the publish URL. The "test" is that the admin
 *    can now make a signed request; a real round-trip is exercised via the
 *    public /api/webhook/publish endpoint.
 *
 *  - outbound_api: validates the provided config + secret shape. Where a real
 *    connectivity check is cheap and safe (e.g. Discord: GET /users/@me), we
 *    attempt it and report the outcome. Network egress failures degrade to a
 *    "configuration valid, connectivity check skipped" result rather than
 *    failing the whole test (02 section 6: graceful degradation).
 *
 * Per 06 section 7: rate limited. Per 06 section 11: audit logged.
 */
export const POST = withPrismaError(async function POST(
  request: Request,
  { params }: { params: Promise<{ id: string }> },
) {
  let user;
  try {
    user = await requireAdmin();
  } catch {
    return withCache(
      NextResponse.json({ error: "Unauthorized" }, { status: 401 }),
      CACHE_NO_STORE,
    );
  }

  const { id } = await params;
  const def = getIntegrationDef(id);
  if (!def) {
    return withCache(
      NextResponse.json({ error: "Unknown integration." }, { status: 400 }),
      CACHE_NO_STORE,
    );
  }

  const rl = rateLimit(`integration-test:${user.id}`, 10, 60_000);
  if (!rl.allowed) {
    return withCache(
      NextResponse.json(
        { error: "Too many test requests. Please slow down." },
        {
          status: 429,
          headers: { "Retry-After": String(Math.ceil(rl.retryAfterMs / 1000)) },
        },
      ),
      CACHE_NO_STORE,
    );
  }

  let body: Record<string, unknown> = {};
  try {
    body = await request.json();
  } catch {
    // Empty body is fine for webhook (uses stored key).
  }

  // ---- webhook -----------------------------------------------------------
  if (def.kind === "webhook") {
    let row = await db.integrationConfig.findUnique({ where: { id } });
    let generated = false;
    let secret = row?.secret ?? "";
    if (!secret) {
      // No stored key yet (or row missing): generate one + enable.
      secret = generateWebhookSecret();
      generated = true;
      row = await db.integrationConfig.upsert({
        where: { id },
        update: { enabled: true, secret },
        create: { id, enabled: true, secret },
      });
    } else if (row && !row.enabled) {
      // Key exists but integration is disabled -> re-enable (keep the key).
      row = await db.integrationConfig.update({
        where: { id },
        data: { enabled: true },
      });
    }
    await logActivity({
      userId: user.id,
      action: "update",
      entity: "integration",
      entityId: id,
      summary: `Tested webhook integration (key ready): ${def.label}`,
    });
    // The raw signing key is surfaced ONLY when it was generated by this
    // request (docs/SECURITY.md: "returned only once ... never retrievable
    // again"). An existing key is never re-revealed here — the admin sees a
    // masked preview and rotates (POST /api/integrations/webhook) to reissue.
    return withCache(
      NextResponse.json({
        ok: true,
        kind: "webhook",
        generated,
        ...(generated ? { secret } : { secretPreview: maskSecret(secret) }),
        publishUrl: "/api/webhook/publish",
        header: "x-aoc-signature",
      }),
      CACHE_NO_STORE,
    );
  }

  // ---- outbound_api ------------------------------------------------------
  // Merge provided config/secret over the stored row (admin may be testing a
  // new credential before saving). Validation runs against the MERGED config,
  // not the delta: the admin UI's Test button sends {} with no config, and a
  // stored, complete configuration must still pass (H1 fix).
  const stored = await db.integrationConfig.findUnique({ where: { id } });
  if (
    body.config !== undefined &&
    (typeof body.config !== "object" ||
      body.config === null ||
      Array.isArray(body.config))
  ) {
    return withCache(
      NextResponse.json(
        { error: "Config must be an object." },
        { status: 400 },
      ),
      CACHE_NO_STORE,
    );
  }
  const mergedRawConfig: Record<string, unknown> = {
    ...parseConfig(stored?.config),
    ...((body.config ?? {}) as Record<string, unknown>),
  };
  const configCheck = validateConfig(id, mergedRawConfig);
  if (!configCheck.valid) {
    return withCache(
      NextResponse.json({ error: configCheck.error }, { status: 400 }),
      CACHE_NO_STORE,
    );
  }
  const mergedConfig = configCheck.config;
  const secret =
    typeof body.secret === "string" && body.secret.trim()
      ? body.secret.trim()
      : (stored?.secret ?? "");

  // Required-field presence check (BOPLA / mass-assignment defense).
  for (const field of def.fields) {
    if (field.required) {
      const has =
        (mergedConfig as Record<string, string>)[field.name] || secret;
      if (!has) {
        return withCache(
          NextResponse.json(
            { error: `${field.label} is required to test this integration.` },
            { status: 400 },
          ),
          CACHE_NO_STORE,
        );
      }
    }
  }

  // Persist the merged config so a successful test is "sticky" (admin doesn't
  // have to re-save). Enabled stays as-is unless the test passes.
  const connectivity = await checkConnectivity(
    def,
    mergedConfig as Record<string, string>,
    secret,
  );

  // Preserve previous enabled when the live check was skipped; only flip on a real check.
  const enabled = connectivity.skipped
    ? (stored?.enabled ?? false)
    : connectivity.ok;
  await db.integrationConfig.upsert({
    where: { id },
    update: {
      config: serializeConfig(mergedConfig as Record<string, string>),
      secret: secret || "",
      enabled,
    },
    create: {
      id,
      config: serializeConfig(mergedConfig as Record<string, string>),
      secret: secret || "",
      enabled,
    },
  });

  await logActivity({
    userId: user.id,
    action: "update",
    entity: "integration",
    entityId: id,
    summary: `Tested ${def.label}: ${connectivity.ok ? "ok" : (connectivity.reason ?? "failed")}`,
  });

  return withCache(
    NextResponse.json({
      ok: connectivity.ok,
      kind: "outbound_api",
      reason: connectivity.reason ?? null,
      skipped: connectivity.skipped ?? false,
    }),
    CACHE_NO_STORE,
  );
});

/**
 * Best-effort connectivity check for an outbound_api integration.
 * Returns { ok, reason, skipped }. `skipped` means the config is valid but a
 * live check wasn't possible (e.g. network egress blocked) — the admin should
 * treat this as "configuration saved, external sync pending".
 */
async function checkConnectivity(
  def: IntegrationDef,
  config: Record<string, string>,
  secret: string,
): Promise<{ ok: boolean; reason: string | null; skipped: boolean }> {
  if (def.id === "discord") {
    try {
      const res = await fetch("https://discord.com/api/v10/users/@me", {
        method: "GET",
        headers: { Authorization: `Bot ${secret}` },
        signal: AbortSignal.timeout(8_000),
      });
      if (res.ok)
        return {
          ok: true,
          reason: "Discord accepted the bot token.",
          skipped: false,
        };
      if (res.status === 401)
        return {
          ok: false,
          reason: "Discord rejected the bot token (401).",
          skipped: false,
        };
      return {
        ok: false,
        reason: `Discord returned HTTP ${res.status}.`,
        skipped: false,
      };
    } catch (e) {
      logger.warn("discord connectivity check failed (network)", {
        error: String(e),
      });
      return {
        ok: true,
        reason: "Config valid; live check skipped (network unavailable).",
        skipped: true,
      };
    }
  }
  // google-workspace / facebook / google-forms: no safe, cheap, credential-
  // less check that works without a real OAuth app. Validate shape only.
  return {
    ok: true,
    reason: "Configuration saved. External sync requires OAuth app setup.",
    skipped: true,
  };
}
